-- Katalog produk awal: 585 barang hasil ekspor dari sistem yang sedang berjalan
-- (ID Produk, Nama Produk, Harga, Stok).
--
-- Yang dipakai hanya tiga kolom pertama. Kolom Stok sengaja dibuang: stok di sistem
-- ini hanya boleh lahir dari kartu_stok lewat dokumen (pembelian, mutasi, stok_opname),
-- tidak ada satu pun tabel master yang menyimpan angka stok. Menyeed stok berarti
-- menulis nilai persediaan tanpa dokumen di belakangnya — persis yang append-only
-- kartu_stok ada untuk mencegah. Saldo awal yang benar dientri sebagai stok_opname
-- atau pembelian setelah katalog ini ada.
--
-- Stok CSV juga bukan product.stok_minimum. Keduanya angka stok, tapi stok_minimum
-- adalah titik pesan ulang, dan 0 di sana berarti "belum pernah diatur" — dibaca
-- GET /product/stok-minimum sebagai penanda untuk melewati barisnya. Mengisinya dengan
-- stok fisik hari ini akan menandai hampir seluruh katalog sebagai butuh dibeli.
--
-- Butuh 002_satuan.sql (satuan dasar dicari berdasarkan nama) dan 004_superadmin.sql
-- (created_by NOT NULL dan menunjuk users) sudah jalan lebih dulu.
--
-- Idempoten: aman dijalankan ulang pada database yang sudah terisi.

-- Data mentahnya disebut sekali di sini, bukan diulang di tiga INSERT di bawah.
-- Tabel sementara, bukan CTE, karena ketiga INSERT itu statement terpisah: masing-masing
-- perlu melihat hasil statement sebelumnya (product_satuan butuh product.id yang baru
-- lahir), dan CTE tidak bisa memberikan itu.
--
-- Tanpa ON COMMIT DROP: berkas ini juga harus benar kalau dijalankan psql tanpa
-- --single-transaction, dan di mode autocommit ON COMMIT DROP membuang tabelnya
-- sebelum sempat diisi.
