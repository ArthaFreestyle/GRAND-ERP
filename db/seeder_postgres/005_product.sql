-- 1. Produk.
--
-- Satuan dasar dan pelaku dicari lewat CROSS JOIN, bukan subquery skalar, mengikuti
-- 004_superadmin.sql: id-nya IDENTITY jadi tidak bisa ditulis literal, dan kalau salah
-- satu belum ada seeder ini tidak memasukkan apa pun alih-alih gagal dengan galat
-- NOT NULL yang tidak menyebut penyebabnya.
--
-- Semua produk masuk dengan satuan dasar PCS. CSV sumbernya tidak membawa satuan sama
-- sekali, dan menebak dari nama ("SIDU A4 S" itu rim atau pak?) akan mengunci faktor
-- konversi yang salah ke setiap dokumen yang dibuat sesudahnya. PCS adalah satu-satunya
-- pilihan yang tidak mengklaim apa pun; satuan yang lebih besar ditambahkan lewat
-- PATCH /product/{id} saat faktornya benar-benar diketahui.
--
-- stok_minimum dibiarkan default 0 — lihat catatan di kepala berkas.
--
-- Target ON CONFLICT persis nama constraint-nya: keunikan kode_barang masih
-- product_kode_barang_key UNIQUE (kode_barang) apa adanya, migrasi 000009 hanya
-- memindahkan keunikan kode master lain ke lower(...), bukan yang ini.
INSERT INTO product (kode_barang, nama, id_satuan_dasar, created_by)
SELECT s.kode_barang, s.nama, sat.id, u.id
FROM seed_product s
CROSS JOIN satuan sat
CROSS JOIN users u
WHERE lower(sat.nama) = 'pcs'
  AND lower(u.username) = 'admin'
ON CONFLICT (kode_barang) DO NOTHING;

-- 2. Baris satuan dasar di product_satuan.
--
-- Tidak ada constraint yang mewajibkannya, tapi produk tanpa baris ini merusak setiap
-- konversi yang dibangun di atasnya — ProductUseCase.Create menyisipkannya sendiri
-- dengan faktor = 1 justru karena skemanya diam. Seeder harus melakukan hal yang sama
-- atau 585 produk ini lahir cacat.
--
-- is_default_input FALSE, sama dengan yang ditulis mergeSatuan untuk satuan dasar yang
-- tidak diminta secara eksplisit, supaya produk hasil seeder tidak bisa dibedakan dari
-- produk hasil POST /product.
INSERT INTO product_satuan (id_product, id_satuan, faktor, is_default_input)
SELECT p.id, p.id_satuan_dasar, 1, FALSE
FROM product p
JOIN seed_product s ON s.kode_barang = p.kode_barang
ON CONFLICT (id_product, id_satuan) DO NOTHING;

-- 3. Harga jual versi pertama.
--
-- berlaku_dari tanggal tetap di masa lalu, bukan CURRENT_DATE: harganya harus sudah
-- berlaku begitu seeder selesai, dan tanggal yang ikut bergeser tiap hari membuat dua
-- kali jalan menghasilkan dua versi yang berbeda. berlaku_sampai NULL = terbuka.
--
-- ON CONFLICT DO NOTHING tanpa menyebut target, satu-satunya di antara seluruh seeder.
-- Tabel ini tidak punya indeks unik untuk disebut; yang menjaganya adalah exclusion
-- constraint GiST product_harga_jual_no_overlap. DO NOTHING tanpa target memang meliputi
-- pelanggaran exclusion, jadi jalan kedua yang harganya sudah ada tidak menabraknya.
INSERT INTO product_harga_jual (id_product, id_satuan, harga, berlaku_dari, created_by)
SELECT p.id, p.id_satuan_dasar, s.harga, DATE '2026-01-01', u.id
FROM product p
JOIN seed_product s ON s.kode_barang = p.kode_barang
CROSS JOIN users u
WHERE lower(u.username) = 'admin'
ON CONFLICT DO NOTHING;

-- 4. Katalog per unit kerja (migrasi 000029).
--
-- Backfill migrasi hanya menjangkau produk yang SUDAH ada saat migrasi jalan. Di
-- database baru migrasi selalu jalan sebelum seeder, jadi tanpa langkah ini ke-585
-- produk di atas lahir dengan katalog kosong dan setiap dokumen ke ruang mana pun
-- ditolak ("tidak ada di katalog unit kerja ruang ini").
--
-- Semua unit AKTIF, sama dengan default POST /product tanpa id_unit_kerja dan dengan
-- backfill migrasinya. Hanya produk yang belum punya keanggotaan sama sekali yang
-- diisi — bukan tiap produk seeder — supaya menjalankan ulang berkas ini tidak
-- membatalkan penyempitan yang sengaja dilakukan lewat PUT /product/{id}/unit-kerja.
INSERT INTO product_unit_kerja (id_product, id_unit_kerja, created_by)
SELECT p.id, uk.id, u.id
FROM product p
JOIN seed_product s ON s.kode_barang = p.kode_barang
CROSS JOIN unit_kerja uk
CROSS JOIN users u
WHERE uk.is_aktif
  AND lower(u.username) = 'admin'
  AND NOT EXISTS (SELECT 1 FROM product_unit_kerja x WHERE x.id_product = p.id)
ON CONFLICT (id_product, id_unit_kerja) DO NOTHING;

